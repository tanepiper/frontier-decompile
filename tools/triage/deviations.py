#!/usr/bin/env python3
"""Collect every known difference from the original into one ledger.

A reimplementation marks each intentional difference from the original with a comment that
contains `Deviation:`, and each piece it leaves out with `not ported` (see the re-port skill).
This tool finds those comments in the source tree and writes them, grouped by file, with links,
so the project always has one up-to-date list of where it differs from the original.

Usage:
  deviations.py [--out FILE] [--check] [DIR ...]

  DIR       folders to scan (default: the current folder)
  --out     where to write the ledger (default: print it)
  --check   with --out: exit 1, without writing, when FILE is out of date (for tests and CI)

What it reads: comment lines starting with `//`, `#`, `--`, `;` or `*` (C, C++, Rust, Go,
JavaScript, Python, shell, Lua, assembly, block comments). Consecutive comment lines form one
block; a block that contains a marker is one entry. Markers (any letter case): `deviation`,
`not ported`. Lines that only cite the original (`Original: ...`) are left out of the text.

What it skips: prose and data files (.md, .txt, .tsv, .json and the like), folders named .git, target, build, analysis, derived, node_modules, .venv
(the game's files and generated output), and files that are not text.

It does not judge the comments: a comment that says "deviation" in passing is listed too.
Keep the marker for real differences.
"""
import os
import re
import sys

SKIP = {'.git', 'target', 'build', 'analysis', 'derived', 'node_modules', '.venv', '__pycache__'}
# Prose and data, where a `#` is a heading or a value, not a comment.
NOT_CODE = ('.md', '.txt', '.tsv', '.csv', '.json', '.html', '.xml', '.yml', '.yaml')
COMMENT = re.compile(r'^\s*(//+!?|#+|--|;+|/?\*+)\s?(.*)$')
MARKERS = [('Deviation', re.compile(r'deviation', re.I)), ('Not ported', re.compile(r'not ported', re.I))]


def blocks(lines):
    """Yield (first line number, text) for each run of comment lines."""
    start, text = None, []
    for i, line in enumerate(lines, 1):
        m = COMMENT.match(line)
        if m and not line.lstrip().startswith('#!'):
            start = start or i
            body = m.group(2).strip().rstrip('*/').strip()
            if body and not body.startswith('Original:'):
                text.append(body)
            continue
        if text:
            yield start, ' '.join(text)
        start, text = None, []
    if text:
        yield start, ' '.join(text)


def collect(dirs):
    """Every marked comment block: (path, line, kind, text), sorted by path and line."""
    found = []
    for top in dirs:
        for dirpath, subdirs, files in os.walk(top):
            subdirs[:] = sorted(d for d in subdirs if d not in SKIP)
            for name in sorted(files):
                if name.lower().endswith(NOT_CODE):
                    continue
                path = os.path.join(dirpath, name)
                try:
                    lines = open(path, encoding='utf-8').read().split('\n')
                except (UnicodeDecodeError, OSError):
                    continue
                for line, text in blocks(lines):
                    kind = next((k for k, r in MARKERS if r.search(text)), None)
                    if kind:
                        found.append((os.path.normpath(path), line, kind, text))
    return sorted(found)


def render(entries, out):
    """The ledger as Markdown. Links are relative to the ledger's folder."""
    base = os.path.dirname(os.path.abspath(out)) if out else os.getcwd()
    counts = {}
    for _, _, kind, _ in entries:
        counts[kind] = counts.get(kind, 0) + 1
    lines = [
        '# Deviations from the original',
        '',
        'Generated by `deviations.py` from comments in the sources: edit the comments, not this',
        'file. Each entry is a place where the reimplementation differs from the original on',
        'purpose, or leaves a piece out.',
        '',
        (', '.join(f'{k}: {n}' for k, n in sorted(counts.items())) or 'No entries') + '.',
    ]
    current = None
    for path, line, kind, text in entries:
        if path != current:
            lines += ['', f'## `{path}`', '']
            current = path
        link = os.path.relpath(os.path.abspath(path), base)
        lines.append(f'- [{kind}] [line {line}]({link}#L{line}): {text}')
    return '\n'.join(lines) + '\n'


def main(argv):
    if '-h' in argv or '--help' in argv:
        print(__doc__)
        return 0
    out, check, dirs = None, False, []
    args = iter(argv)
    for a in args:
        if a == '--out':
            out = next(args, None)
        elif a == '--check':
            check = True
        else:
            dirs.append(a)
    text = render(collect(dirs or ['.']), out)
    if not out:
        sys.stdout.write(text)
        return 0
    if check:
        old = open(out, encoding='utf-8').read() if os.path.exists(out) else ''
        if old != text:
            print(f'{out} is out of date: run deviations.py --out {out}')
            return 1
        print(f'{out} is up to date')
        return 0
    with open(out, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {out} ({text.count(chr(10) + "- [")} entries)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
