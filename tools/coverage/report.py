"""Compare the coverage runs of tools/coverage/scenarios.tsv and list the code each action runs.

Usage: ./gameframe python tools/coverage/report.py [--cov DIR] [--export DIR] [--out FILE]

  --cov DIR      the runs (default game-data/derived/coverage)
  --export DIR   the Ghidra export (default analysis/export)
  --out FILE     the report (default DIR/report.md; git-ignored, it lists addresses only)

For each run and its baseline, and each image, it runs GameFrame's coverdiff on the two logs and
sorts the instructions only the action ran into the export's functions, by start and size (coverdiff
alone credits any address to the nearest function start before it). Code outside every function is
grouped under the nearest call target the runs saw before it.

It also writes DIR/seeds/IMAGE.entries (every call target the runs saw) and
DIR/seeds/IMAGE.cov (every instruction any run executed), which tools/ghidra/SeedFunctions.java
reads to create functions and disassemble executed code. And DIR/functions/IMAGE.tsv, the export's
functions with flat addresses, because coverdiff skips segment:offset rows.
"""
import bisect, json, os, subprocess, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def opt(argv, name, default):
    return argv[argv.index(name) + 1] if name in argv else default


def flat(addr):
    seg, off = addr.split(':')
    return int(seg, 16) * 16 + int(off, 16)


def functions(path):
    """[(flat start, size, name, 'seg:off')] from a Ghidra functions.tsv."""
    rows = []
    if os.path.exists(path):
        for line in open(path, encoding='utf-8', errors='replace'):
            p = line.rstrip('\n').split('\t')
            if len(p) >= 3 and ':' in p[0]:
                rows.append((flat(p[0]), int(p[1]), p[2], p[0]))
    rows.sort()
    return rows


def segments(funcs):
    segs = sorted({int(a.split(':')[0], 16) for _, _, _, a in funcs} | {0x1000})
    return segs


def seg_off(segs, f):
    s = [x for x in segs if x * 16 <= f][-1]
    return f'{s:04x}:{f - s * 16:04x}'


def read_set(path):
    if not os.path.exists(path):
        return set()
    return {int(x, 16) for x in open(path).read().split()}


class Image:
    def __init__(self, name, export):
        self.name = name
        self.funcs = functions(os.path.join(export, name, 'functions.tsv'))
        self.starts = [f[0] for f in self.funcs]
        self.segs = segments(self.funcs)

    def find(self, a):
        """The function whose [start, start+size) holds `a`, else None."""
        i = bisect.bisect_right(self.starts, a) - 1
        if i >= 0 and a < self.funcs[i][0] + max(self.funcs[i][1], 1):
            return self.funcs[i]
        return None

    def at(self, f):
        return seg_off(self.segs, f)


def main(argv):
    if argv and argv[0] in ('-h', '--help'):
        print(__doc__)
        return 0
    cov = opt(argv, '--cov', os.path.join(ROOT, 'game-data/derived/coverage'))
    export = opt(argv, '--export', os.path.join(ROOT, 'analysis/export'))
    out = opt(argv, '--out', os.path.join(cov, 'report.md'))
    runs = []
    for line in open(os.path.join(ROOT, 'tools/coverage/scenarios.tsv')):
        if line.startswith('#') or not line.strip():
            continue
        p = line.rstrip('\n').split('\t')
        runs.append((p[0], p[1], p[4]))
    names = sorted({f[:-4] for r, _, _ in runs if os.path.isdir(os.path.join(cov, r))
                    for f in os.listdir(os.path.join(cov, r)) if f.endswith('.cov') and f != 'linear.cov'})
    images = {n: Image(n, export) for n in names}

    # Union over every run: what ran, and every routine entry seen.
    ran, entries = defaultdict(set), defaultdict(set)
    for r, _, _ in runs:
        for n in names:
            ran[n] |= read_set(os.path.join(cov, r, n + '.cov'))
            entries[n] |= read_set(os.path.join(cov, r, n + '.entries'))

    os.makedirs(os.path.join(cov, 'seeds'), exist_ok=True)
    os.makedirs(os.path.join(cov, 'functions'), exist_ok=True)
    lines = ['# Coverage report (generated by tools/coverage/report.py)', '',
             '## Every run together', '',
             '| Image | Instructions run | In known functions | Outside | Entries seen | Entries not a function start | Functions run / known |',
             '|---|---|---|---|---|---|---|']
    for n in names:
        im = images[n]
        with open(os.path.join(cov, 'functions', n + '.tsv'), 'w') as f:
            for a, size, name, _ in im.funcs:
                f.write(f'{a:x}\t{size}\t{name}\n')
        outside = {a for a in ran[n] if im.find(a) is None}
        new = sorted(e for e in entries[n] if e not in set(im.starts))
        with open(os.path.join(cov, 'seeds', n + '.entries'), 'w') as f:
            f.write(''.join(f'{e:x}\n' for e in sorted(entries[n])))
        with open(os.path.join(cov, 'seeds', n + '.cov'), 'w') as f:
            f.write(''.join(f'{a:x}\n' for a in sorted(ran[n])))
        hit = {im.find(a)[0] for a in ran[n] if im.find(a)}
        lines.append(f'| {n} | {len(ran[n])} | {len(ran[n]) - len(outside)} | {len(outside)} | '
                     f'{len(entries[n])} | {len(new)} | {len(hit)} / {len(im.funcs)} |')

    # Per action: coverdiff, then sort into functions.
    gf = os.path.join(ROOT, 'gameframe')
    used_by = defaultdict(set)  # (image, function or new routine address) -> actions
    for r, base, what in runs:
        if base == '-' or not os.path.isdir(os.path.join(cov, r)):
            continue
        lines += ['', f'## {r} (baseline {base})', '', what, '']
        total = 0
        for n in names:
            a_log, b_log = (os.path.join(cov, x, n + '.cov') for x in (base, r))
            if not os.path.exists(b_log):
                continue
            if not os.path.exists(a_log):
                a_log = os.devnull
            res = subprocess.run([gf, 'run', 'coverdiff', a_log, b_log, '--functions',
                                  os.path.join(cov, 'functions', n + '.tsv'), '--json'],
                                 capture_output=True, text=True, check=True)
            rep = json.loads(res.stdout[res.stdout.index('{'):])
            only = sorted(int(b, 16) for g in rep['only_action'] for b in g['blocks'])
            if not only:
                continue
            total += len(only)
            im = images[n]
            known, unknown = defaultdict(list), defaultdict(list)
            ents = sorted(entries[n])
            for a in only:
                f = im.find(a)
                if f:
                    known[f].append(a)
                else:
                    i = bisect.bisect_right(ents, a) - 1
                    unknown[ents[i] if i >= 0 else a].append(a)
            lines.append(f'**{n}**: {len(only)} instructions only with the action, '
                         f'{len(known)} known functions, {len(unknown)} new routines')
            lines.append('')
            for f, bl in sorted(known.items()):
                lines.append(f'- `{f[3]}` {f[2]} ({len(bl)})')
                used_by[(n, f[3], f[2])].add(r)
            for e, bl in sorted(unknown.items()):
                lines.append(f'- `{im.at(e)}` new, {im.at(bl[0])}–{im.at(bl[-1])} ({len(bl)})')
                used_by[(n, im.at(e), 'new')].add(r)
            lines.append('')
        if total == 0:
            lines.append('No instruction ran only with the action.')
    # Code that only one action brought in: the strongest hint of what it does.
    lines += ['', '## Functions only one action ran', '',
              '| Action | Image | Function | Name |', '|---|---|---|---|']
    for (n, a, name), acts in sorted(used_by.items(), key=lambda kv: (sorted(kv[1]), kv[0])):
        if len(acts) == 1:
            lines.append(f'| {next(iter(acts))} | {n} | `{a}` | {name} |')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'wrote {out}')
    print('\n'.join(lines[:8 + len(names)]))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
